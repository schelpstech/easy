CREATE TABLE IF NOT EXISTS rate_cards (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    origin_zone_id BIGINT UNSIGNED NOT NULL,
    destination_zone_id BIGINT UNSIGNED NOT NULL,
    service_code VARCHAR(40) NOT NULL,
    service_name VARCHAR(80) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'NGN',
    base_fee DECIMAL(14,2) NOT NULL,
    base_weight_kg DECIMAL(10,2) NOT NULL DEFAULT 1.00,
    extra_kg_fee DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    minimum_fee DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    fuel_percent DECIMAL(7,3) NOT NULL DEFAULT 0.000,
    insurance_percent DECIMAL(7,3) NOT NULL DEFAULT 0.000,
    packaging_fee DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    tax_percent DECIMAL(7,3) NOT NULL DEFAULT 0.000,
    volumetric_divisor DECIMAL(10,2) NOT NULL DEFAULT 5000.00,
    estimated_days_min SMALLINT UNSIGNED NULL,
    estimated_days_max SMALLINT UNSIGNED NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active',
    created_by BIGINT UNSIGNED NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_rate_route_service (origin_zone_id, destination_zone_id, service_code),
    KEY idx_rate_cards_status (status),
    CONSTRAINT fk_rates_origin FOREIGN KEY (origin_zone_id) REFERENCES rate_zones (id),
    CONSTRAINT fk_rates_destination FOREIGN KEY (destination_zone_id) REFERENCES rate_zones (id),
    CONSTRAINT fk_rates_staff FOREIGN KEY (created_by) REFERENCES staff_users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    booking_number VARCHAR(30) NOT NULL,
    customer_id BIGINT UNSIGNED NOT NULL,
    origin_zone_id BIGINT UNSIGNED NOT NULL,
    destination_zone_id BIGINT UNSIGNED NOT NULL,
    pickup_address_id BIGINT UNSIGNED NOT NULL,
    delivery_address_id BIGINT UNSIGNED NOT NULL,
    pickup_snapshot_json JSON NOT NULL,
    delivery_snapshot_json JSON NOT NULL,
    service_code VARCHAR(40) NOT NULL,
    service_name VARCHAR(80) NOT NULL,
    package_description VARCHAR(500) NOT NULL,
    weight_kg DECIMAL(10,2) NOT NULL,
    length_cm DECIMAL(10,2) NULL,
    width_cm DECIMAL(10,2) NULL,
    height_cm DECIMAL(10,2) NULL,
    volumetric_weight_kg DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    chargeable_weight_kg DECIMAL(10,2) NOT NULL,
    declared_value DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    is_fragile TINYINT(1) NOT NULL DEFAULT 0,
    packaging_required TINYINT(1) NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL DEFAULT 'NGN',
    base_amount DECIMAL(14,2) NOT NULL,
    weight_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    fuel_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    insurance_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    packaging_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    tax_amount DECIMAL(14,2) NOT NULL DEFAULT 0.00,
    total_amount DECIMAL(14,2) NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'awaiting_payment',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'unpaid',
    shipment_id BIGINT UNSIGNED NULL,
    quote_expires_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_bookings_number (booking_number),
    UNIQUE KEY uq_bookings_shipment (shipment_id),
    KEY idx_bookings_customer_created (customer_id, created_at),
    KEY idx_bookings_status_created (status, created_at),
    CONSTRAINT fk_bookings_customer FOREIGN KEY (customer_id) REFERENCES customer_users (id),
    CONSTRAINT fk_bookings_origin FOREIGN KEY (origin_zone_id) REFERENCES rate_zones (id),
    CONSTRAINT fk_bookings_destination FOREIGN KEY (destination_zone_id) REFERENCES rate_zones (id),
    CONSTRAINT fk_bookings_pickup FOREIGN KEY (pickup_address_id) REFERENCES customer_addresses (id),
    CONSTRAINT fk_bookings_delivery FOREIGN KEY (delivery_address_id) REFERENCES customer_addresses (id),
    CONSTRAINT fk_bookings_shipment FOREIGN KEY (shipment_id) REFERENCES shipments (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

